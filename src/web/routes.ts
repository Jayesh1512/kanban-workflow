/** Exact W1 route inventory. Withdrawal remains a protected, deferred action. */
export function routeInventory(): { method: string; path: string; public: boolean }[] {
  const publicRoutes = [
    ['GET', '/login'],
    ['POST', '/login'],
    ['GET', '/static/app.css'],
    ['GET', '/static/app.js'],
  ];
  const protectedGets = [
    '/',
    '/board',
    '/board/fragment',
    '/board/version',
    '/cards/:id',
    '/review',
    '/review/:id',
    '/lanes',
    '/lanes/:id',
    '/companies',
    '/companies/:id',
    '/contacts',
    '/contacts/:id',
    '/search',
    '/log',
    '/settings',
    '/settings/teammates',
    '/settings/credentials',
    '/settings/accounts',
    '/settings/accounts/:id/chats',
  ];
  const protectedPosts = [
    '/logout',
    '/cards',
    '/cards/:id',
    '/cards/:id/move',
    '/cards/:id/archive',
    '/cards/:id/unarchive',
    '/messages/:id/attach',
    '/review/:id/accept',
    '/review/:id/change',
    '/review/:id/dismiss',
    '/lanes',
    '/lanes/:id',
    '/lanes/:id/archive',
    '/companies/:id',
    '/companies/:id/aliases',
    '/contacts/:id',
    '/contacts/:id/role',
    '/contacts/:id/companies',
    '/contacts/:id/companies/:companyId/remove',
    '/references/:id/remove',
    '/settings',
    '/settings/teammates',
    '/settings/teammates/:id/remove',
    '/settings/credentials',
    '/settings/credentials/:id/revoke',
    '/settings/accounts',
    '/settings/accounts/:id/login',
    '/settings/accounts/:id/disconnect',
    '/settings/accounts/:id/chats/include',
    '/settings/accounts/:id/chats/exclude',
    '/settings/accounts/:id/chats/:chatId/confirm',
    '/settings/accounts/:id/chats/:chatId/withdraw',
  ];
  return [
    ...publicRoutes.map(([method, path]) => ({ method: method as string, path: path as string, public: true })),
    ...protectedGets.map((path) => ({ method: 'GET', path, public: false })),
    ...protectedPosts.map((path) => ({ method: 'POST', path, public: false })),
  ];
}
